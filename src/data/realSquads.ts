const BOOT_PALETTE = ['#D9F938', '#F97316', '#38BDF8', '#F43F5E', '#FFFFFF', '#10B981', '#FACC15'];

function hashSeed(str: string): number {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h);
}

function getRegionalProfile(countryCode: string, confederation?: Confederation): RegionalProfile {
  if (REGIONAL_PROFILES[countryCode]) return REGIONAL_PROFILES[countryCode];
  if (['URU', 'COL', 'CHL', 'PER', 'ECU', 'PAR', 'VEN', 'BOL'].includes(countryCode)) {
    return REGIONAL_PROFILES.ARG;
  }
  if (['POR'].includes(countryCode)) return REGIONAL_PROFILES.ESP;
  if (['NED', 'BEL', 'DEN', 'SWE', 'NOR', 'AUT', 'SUI'].includes(countryCode)) {
    return REGIONAL_PROFILES.GER;
  }
  if (['SCO', 'WAL', 'IRL', 'NIR', 'AUS', 'NZL'].includes(countryCode)) {
    return REGIONAL_PROFILES.ENG;
  }
  if (confederation === 'CAF') return REGIONAL_PROFILES.CAF;
  if (confederation === 'AFC') return REGIONAL_PROFILES.AFC;
  if (confederation === 'CONCACAF') return REGIONAL_PROFILES.CONCACAF;
  if (confederation === 'CONMEBOL') return REGIONAL_PROFILES.ARG;
  return REGIONAL_PROFILES.ESP;
}

/**
 * Genera el nombre regional para un futbolista procedural evitando nombres genéricos repetidos.
 */
export function generateRegionalProceduralName(
  teamId: string,
  countryCode: string,
  confederation: Confederation,
  slotIndex: number
): string {
  const prof = getRegionalProfile(countryCode, confederation);
  const h1 = hashSeed(`${teamId}_fn_${slotIndex}`);
  const h2 = hashSeed(`${teamId}_ln_${slotIndex * 13 + 7}`);
  const first = prof.firstNames[(h1 + slotIndex) % prof.firstNames.length];
  const last = prof.lastNames[(h2 + slotIndex * 3) % prof.lastNames.length];
  return `${first} ${last}`;
}

/**
 * Construye el objeto completo `PlayerAppearance` (`aspecto`) para cualquier jugador (real o procedural).
 */
export function buildPlayerAppearance(
  playerName: string,
  role: PlayerPosition,
  countryCode: string,
  confederation: Confederation,
  preferredFoot: 'Derecho' | 'Izquierdo' | 'Ambidiestro',
  explicitHeightCm?: number,
  explicitAspecto?: Partial<PlayerAppearance>
): PlayerAppearance {
  const star = STAR_PLAYER_APPEARANCES[playerName];
  const prof = getRegionalProfile(countryCode, confederation);
  const h = hashSeed(`${playerName}|${countryCode}|${role}`);

  const defaultHeight =
    role === 'GK'
      ? 188 + (h % 11)
      : role === 'CB'
      ? 185 + (h % 10)
      : role === 'ST'
      ? 178 + (h % 15)
      : role === 'LW' || role === 'RW' || role === 'CAM'
      ? 170 + (h % 13)
      : 175 + (h % 13);

  const footCode: PreferredFootCode =
    preferredFoot === 'Izquierdo' ? 'I' : preferredFoot === 'Ambidiestro' ? 'A' : 'D';

  return {
    tonoPiel:
      explicitAspecto?.tonoPiel ??
      star?.tonoPiel ??
      prof.skinTones[h % prof.skinTones.length],
    peinado:
      explicitAspecto?.peinado ??
      star?.peinado ??
      prof.hairstyles[(h >> 3) % prof.hairstyles.length],
    colorPelo:
      explicitAspecto?.colorPelo ??
      star?.colorPelo ??
      prof.hairColors[(h >> 5) % prof.hairColors.length],
    barba:
      explicitAspecto?.barba ??
      star?.barba ??
      prof.beards[(h >> 7) % prof.beards.length],
    alturaCm:
      explicitAspecto?.alturaCm ??
      star?.alturaCm ??
      explicitHeightCm ??
      defaultHeight,
    colorBotines:
      explicitAspecto?.colorBotines ??
      star?.colorBotines ??
      BOOT_PALETTE[(h >> 9) % BOOT_PALETTE.length],
    piernaHabil:
      explicitAspecto?.piernaHabil ??
      star?.piernaHabil ??
      footCode,
  };
}
